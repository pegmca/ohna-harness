import { JSDOM } from "../apps/ohna-web/node_modules/jsdom/lib/api.js";
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
const require = createRequire(import.meta.url);
const dom = new JSDOM("<!doctype html><html><body></body></html>");
globalThis.window = dom.window;
globalThis.document = dom.window.document;
globalThis.DOMParser = dom.window.DOMParser;
const context = new Proxy({}, { get: () => () => ({}), set: () => true });
dom.window.HTMLCanvasElement.prototype.getContext = () => context;
try { Object.defineProperty(globalThis, "navigator", { value: dom.window.navigator, configurable: true }); } catch {}
const lottie = require("../apps/ohna-web/node_modules/lottie-web/build/player/lottie_light");
const id = process.argv[2];
const frame = Number(process.argv[3] || 239);
const source = id === "reference" ? new URL("../apps/ohna-web/src/assets/lottie/infinity-trace.json", import.meta.url) : new URL(`../apps/ohna-web/src/assets/lottie/awards/${id}.json`, import.meta.url);
const data = JSON.parse(readFileSync(source, "utf8"));
const container = document.createElement("div");
document.body.appendChild(container);
const anim = lottie.loadAnimation({ container, renderer: "svg", loop: false, autoplay: false, animationData: data });
anim.goToAndStop(frame, true);
const svg = container.querySelector("svg");
if (!svg) throw new Error("missing svg");
svg.setAttribute("width", "480"); svg.setAttribute("height", "480");
writeFileSync(`/tmp/lottie-awards/verified-${id}-${frame}.svg`, svg.outerHTML.replaceAll('stroke-miterlimit="undefined"', 'stroke-miterlimit="4"'));
console.log(`${id} frame ${frame}: rendered, layers=${data.layers.length}`);
anim.destroy();
process.exit(0);
